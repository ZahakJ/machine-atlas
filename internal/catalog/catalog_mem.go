// allocstall declares the direct-reclaim counter of one zone. The kernel
// counts an entry into direct reclaim (do_try_to_free_pages, global reclaim
// only) under the highest zone the allocation may use, gfp_zone() of its
// flags: user pages (GFP_HIGHUSER_MOVABLE) count under Movable whether or
// not any memory is in ZONE_MOVABLE, most kernel allocations under Normal.
func allocstall(key, zone string) Entry {
	return vmstat("allocstall_"+key, obs.UnitCount, "Direct reclaim entries (highest zone "+zone+")",
		"Times since boot that an allocating task entered direct reclaim, reclaiming memory itself before its allocation could proceed, for allocations whose highest allowed zone (the zone their GFP flags select) is "+zone+". It counts entries into reclaim, not time spent or pages freed, and is not about memory \"in\" the "+zone+" zone.",
		"Reclaim triggered by a memory cgroup reaching its limit is not counted here. User pages count under Movable even when no memory is in that zone; kernel allocations mostly under Normal. A kernel built without this zone has no such counter. "+cumulative)
}

