package catalog

import "github.com/ZahakJ/machine-atlas/internal/obs"

// meminfo declares one /proc/meminfo field, reported in bytes.
func meminfo(field, title, desc, caveat string) Entry {
	return Entry{
		ID: "mem.meminfo." + field, Title: title, Description: desc,
		Unit: obs.UnitBytes, Type: obs.TypeInt, Kind: obs.KindLive, Scope: obs.ScopeKernel,
		Caveat: caveat, Privileged: privSame,
	}
}

// meminfoStatic declares a /proc/meminfo field that is fixed at boot (or
// changes only through hotplug), so it is static configuration rather than
// a live measurement.
func meminfoStatic(field, title, desc, caveat string) Entry {
	e := meminfo(field, title, desc, caveat)
	e.Kind = obs.KindStatic
	return e
}

// hugetlbCount declares one of the HugePages_* meminfo lines, which are page
// counts rather than kB.
func hugetlbCount(field, title, desc string) Entry {
	e := meminfo(field, title, desc, "Describes only the hugetlbfs pool of the default huge page size; transparent huge pages are counted in AnonHugePages instead. Other sizes are in mem.hugepages.sizes.")
	e.Unit = obs.UnitCount
	return e
}

