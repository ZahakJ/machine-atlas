// Derived facts are computed from a snapshot's observations by
// internal/derive. They are declared here so lessons can reference them and
// the inspector can explain them; the rule and inputs of each computed value
// travel with the fact itself.

const derivedPrivileged = "Root would not change the rule; it can only make more inputs available."

// derived declares one derived fact.
func derived(id, typ, unit, basis, title, desc, caveat string) Entry {
	return Entry{
		ID: "derived." + id, Title: title, Description: desc, Unit: unit, Type: typ,
		Basis: basis, Caveat: caveat, Privileged: derivedPrivileged,
	}
}

