package catalog

import "github.com/ZahakJ/machine-atlas/internal/obs"

// Network observations: interfaces, addresses, routes, sockets, protocol
// counters, softirq statistics, queueing disciplines, connection tracking
// and the net.* sysctls. Almost everything under /proc/net describes the
// network namespace atlas runs in, which in a container is not the host's.

const (
	netnsCaveat = "Describes atlas's network namespace: in a container these are the container's own interfaces, routes and sockets, not the host's."
	netCounter  = "A counter since boot (or since the network namespace was created), shared by IPv4 and IPv6 where the MIB is: one reading cannot give a rate; take two readings and subtract."
)

// ifaceColumn is the namespace strict redaction numbers interface names
// in, so <if-2> is the same interface in every table.
const ifaceColumn = "if"

// netSysctl declares one integer tunable under /proc/sys/net.
func netSysctl(name, unit string, scope obs.Scope, title, desc, caveat string) Entry {
	return Entry{
		ID: "net.sysctl." + name, Title: title, Description: desc, Unit: unit,
		Type: obs.TypeInt, Kind: obs.KindStatic, Scope: scope, Caveat: caveat, Privileged: privSame,
	}
}

// netSysctlString declares one textual tunable under /proc/sys/net.
func netSysctlString(name string, scope obs.Scope, title, desc, caveat string) Entry {
	e := netSysctl(name, "", scope, title, desc, caveat)
	e.Type = obs.TypeString
	return e
}

// snmp declares one counter of /proc/net/snmp or /proc/net/netstat; file
// is "snmp" or "netstat", group the line prefix ("Tcp", "TcpExt").
func snmp(file, group, name, unit, title, desc, caveat string) Entry {
	return Entry{
		ID: "net." + file + "." + group + "." + name, Title: title, Description: desc, Unit: unit,
		Type: obs.TypeInt, Kind: obs.KindLive, Scope: obs.ScopeNamespace, Caveat: caveat, Privileged: privSame,
	}
}

// sockstat declares one figure of /proc/net/sockstat or sockstat6.
func sockstat(id, unit, title, desc, caveat string) Entry {
	return Entry{
		ID: "net." + id, Title: title, Description: desc, Unit: unit,
		Type: obs.TypeInt, Kind: obs.KindLive, Scope: obs.ScopeNamespace, Caveat: caveat, Privileged: privSame,
	}
}

// addressTable declares an address table; the address itself is replaced
// by every redaction policy, its computed class and scope survive.
func addressTable(family, title, desc, source string) Entry {
	return Entry{
		ID: "net.addresses." + family, Title: title, Description: desc,
		Type:    obs.TypeTable,
		Columns: []string{"interface", "address", "prefix_len", "scope", "class", "dynamic", "temporary"},
		Kind:    obs.KindLive, Scope: obs.ScopeNamespace,
		ColumnSensitivity:  map[string]Sensitivity{"address": Address},
		IdentifyingColumns: []string{"interface"}, SharedIdentifiers: map[string]string{"interface": ifaceColumn},
		Caveat:     "Only the addresses of atlas's network namespace. The address cells are replaced by every redaction policy; class (loopback, link-local, private, ula, cgnat, multicast, global) is computed from the address at collection and survives. " + source,
		Privileged: "Nothing: every user may list the addresses of their own namespace.",
	}
}

// routeTable declares a routing table; destination and gateway are
// replaced by every redaction policy.
func routeTable(family, title, desc, caveat string) Entry {
	return Entry{
		ID: "net.routes." + family, Title: title, Description: desc,
		Type: obs.TypeTable,
		Columns: []string{"interface", "destination", "prefix_len", "destination_class", "gateway", "via_gateway",
			"metric", "default", "type"},
		Kind: obs.KindLive, Scope: obs.ScopeNamespace,
		ColumnSensitivity:  map[string]Sensitivity{"destination": Address, "gateway": Address},
		IdentifyingColumns: []string{"interface"}, SharedIdentifiers: map[string]string{"interface": ifaceColumn},
		Caveat:     caveat + " Destination and gateway cells are replaced by every redaction policy; their computed classes and the default and via_gateway flags survive.",
		Privileged: privSame,
	}
}

