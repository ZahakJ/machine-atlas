NODEV_BASE = ['sysfs', 'tmpfs', 'bdev', 'proc', 'cgroup', 'cgroup2', 'cpuset', 'devtmpfs', 'configfs', 'debugfs',
              'tracefs', 'securityfs', 'sockfs', 'bpf', 'pipefs', 'ramfs', 'hugetlbfs', 'devpts', 'mqueue',
              'pstore', 'efivarfs']


def generate(r, m):
    s = STORAGE[m['name']]
    rng = random.Random(m['name'] + ':storage')
    names = {d['name'] for d in m.get('block', [])}
    for d in s['disks']:
        assert d['name'] in names, (m['name'], d['name'])
        write_disk(r, m, d, rng)
    write_filesystems(r, m, s)
    if s.get('deny'):
        meta_path = os.path.join(r.dir, '_meta.json')
        with open(meta_path) as f:
            meta = json.load(f)
        meta['deny'] = meta['deny'] + s['deny']
        with open(meta_path, 'w') as f:
            f.write(json.dumps(meta, indent=2) + '\n')
    m['readme'] = m['readme'].rstrip() + '\n' + s['readme']


def symlink(r, path, target):
    p = os.path.join(r.dir, path.lstrip('/'))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    if os.path.lexists(p):
        os.remove(p)
    os.symlink(target, p)


def write_disk(r, m, d, rng):
    v = m['kver']
    b = f'/sys/block/{d["name"]}'
    q = b + '/queue'
    r.w(f'{q}/physical_block_size', f'{d["pbs"]}\n')
    r.w(f'{q}/nr_requests', f'{d["nr"]}\n')
    r.w(f'{q}/max_sectors_kb', f'{d["max_kb"]}\n')
    r.w(f'{q}/max_hw_sectors_kb', f'{d["max_hw_kb"]}\n')
    r.w(f'{q}/discard_max_bytes', f'{d["discard"]}\n')
    r.w(f'{q}/read_ahead_kb', f'{d["ra"]}\n')
    r.w(f'{q}/write_cache', d['wc'] + '\n')
    if d['lbs'] != 512:
        r.w(f'{q}/logical_block_size', f'{d["lbs"]}\n')
    if ver_ge(v, 4, 18):
        r.w(f'{q}/fua', f'{d["fua"]}\n')
    if d['wbt'] is not None:
        r.w(f'{q}/wbt_lat_usec', f'{d["wbt"]}\n')
    if d['hwq']:
        cpus = [c['cpu'] for c in m['cpus']]
        per = max(1, len(cpus) // d['hwq'])
        for i in range(d['hwq']):
            mine = cpus[i * per:(i + 1) * per] if i < d['hwq'] - 1 else cpus[i * per:]
            r.w(f'{b}/mq/{i}/cpu_list', ', '.join(str(c) for c in mine) + '\n')
    if d['bdi']:
        r.w(f'{b}/bdi/read_ahead_kb', f'{d["ra"]}\n')
        r.w(f'{b}/bdi/min_ratio', '0\n')
        r.w(f'{b}/bdi/max_ratio', '100\n')
        r.w(f'{b}/bdi/stable_pages_required', '0\n')
        if ver_ge(v, 6, 2):
            r.w(f'{b}/bdi/strict_limit', '0\n')
            r.w(f'{b}/bdi/max_bytes', f'{dirty_limit_bytes(r, m)}\n')
            r.w(f'{b}/bdi/min_bytes', '0\n')
            r.w(f'{b}/bdi/max_ratio_fine', '1000000\n')
            r.w(f'{b}/bdi/min_ratio_fine', '0\n')
    r.w(f'{b}/stat', stat_line(m, d, rng))
    # The links that let a mount's device be traced to this disk.
    up = '../..'
    symlink(r, f'/sys/class/block/{d["name"]}', up + d['sysdir'])
    symlink(r, f'/sys/dev/block/{d["devno"]}', up + d['sysdir'])
    for part, devno in d['parts']:
        symlink(r, f'/sys/class/block/{part}', up + d['sysdir'] + '/' + part)
        symlink(r, f'/sys/dev/block/{devno}', up + d['sysdir'] + '/' + part)


def dirty_limit_bytes(r, m):
    """bdi/max_bytes: the global dirty threshold the kernel last computed,
    which with max_ratio 100 is this device's ceiling (nr_dirty_threshold
    from the root's own /proc/vmstat, in bytes)."""
    with open(os.path.join(r.dir, 'proc/vmstat')) as f:
        for line in f:
            k, val = line.split()
            if k == 'nr_dirty_threshold':
                return int(val) * m['page_size']
    raise KeyError('nr_dirty_threshold')


def stat_line(m, d, rng):
    """Documentation/block/stat.rst: 11 fields, 15 from 4.18, 17 from 5.5."""
    v, up = m['kver'], m['uptime']
    pgpgin = up * m['rates']['pgpgin']          # KiB read from block devices since boot
    pgpgout = pgpgin * 1.6                       # as machine.vmstat writes pgpgout
    rkib, wkib = pgpgin * d['share_r'], pgpgout * d['share_w']
    reads = int(rkib / d['rkb'])
    writes = int(wkib / d['wkb'])
    rsec, wsec = int(rkib * 2), int(wkib * 2)
    rms = int(reads * d['rlat'] * rng.uniform(0.97, 1.03))
    wms = int(writes * d['wlat'] * rng.uniform(0.97, 1.03))
    discards = int(up * d['discard_rate'])
    dms = discards * 2
    flushes = int(up * d['flush_rate'])
    fms = int(flushes * 1.3)
    # Weighted time is the sum of every request's time in flight; io_ticks
    # counts a millisecond once however many requests overlapped in it, so
    # their ratio is the average depth while busy.
    weighted = rms + wms + (dms if ver_ge(v, 4, 18) else 0) + (fms if ver_ge(v, 5, 5) else 0)
    io_ms = min(int(weighted / d['depth']), int(up * 1000 * 0.999))
    f = [reads, int(reads * d['merge']), rsec, rms, writes, int(writes * d['merge']), wsec, wms,
         rng.choice([0, 1, 2]) if d['depth'] > 2 else 0, io_ms, weighted]
    if ver_ge(v, 4, 18):
        f += [discards, 0, discards * 2048 * 8, dms]
    if ver_ge(v, 5, 5):
        f += [flushes, fms]
    return ' '.join(f'{n:>8}' for n in f) + '\n'


def write_filesystems(r, m, s):
    lines = [f'nodev\t{n}' for n in NODEV_BASE]
    lines += [f'\t{n}' for n in s['filesystems']]
    lines += [f'nodev\t{n}' for n in s['nodev_extra']]
    r.w('/proc/filesystems', '\n'.join(lines) + '\n')
