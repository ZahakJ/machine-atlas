"""Storage files for the fixture machines: the rest of each block device's
queue/ directory (block sizes, request sizes, nr_requests, write cache, FUA,
discard, readahead, writeback throttling), its blk-mq hardware queues (mq/),
its I/O counters (stat), its backing device info (bdi/), the /sys/class/block
and /sys/dev/block links that tie mounted partitions to their disks, and
/proc/filesystems.

Called from machine.generate after the other generators, with a random
generator of its own so their numbers do not shift. The device names are
those of each machine's `block` list (which also sets the scheduler and the
rotational flag); per-machine choices live in STORAGE below. Every value is
invented. Each device's byte counters are shares of what /proc/vmstat's
pgpgin and pgpgout say was read and written since boot (a device-mapper
volume and the disk beneath it both count the same data), and the busy time
follows from the summed request times and an average depth.
"""
import json
import os
import random

from genlib import ver_ge


def disk(name, devno, sysdir, parts=(), **kw):
    """One whole device. sysdir is its directory under /sys/devices; parts
    lists (name, devno) of its partitions. kw sets queue attributes and the
    I/O profile: share_r/share_w of the machine's pgpgin/pgpgout, rkb/wkb
    (average request size in KiB), rlat/wlat (average ms per request),
    depth (average requests in flight while busy, which sets io_ticks from
    the summed request times), merge (merged per completed)."""
    d = dict(name=name, devno=devno, sysdir=sysdir, parts=list(parts), lbs=512, pbs=512, nr=64, max_kb=1280,
             max_hw_kb=32767, wc='write back', fua=0, discard=0, ra=128, wbt=2000, hwq=1, bdi=True,
             share_r=0.0, share_w=0.0, rkb=64, wkb=96, rlat=0.5, wlat=1.0, depth=1.2, merge=0.2,
             flush_rate=0.0, discard_rate=0.0)
    d.update(kw)
    return d


